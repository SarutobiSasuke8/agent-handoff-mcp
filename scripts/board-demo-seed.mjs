#!/usr/bin/env node
/**
 * Seed the Agent Handoff Board single-tenant demo workspace on a FRESH volume.
 *
 * Creates a registry with four synthetic identities, issues an expiring bearer token for
 * each (only SHA-256 digests are written to the registry), enables them, and creates five
 * example handoffs in different lifecycle states through the normal service layer, so
 * every seeded record passes the same policy checks as a real client call.
 *
 * Refuses to run if the registry or database already exists. Requires a build (dist/).
 *
 * Usage:
 *   node scripts/board-demo-seed.mjs [--registry <path>] [--db <path>]
 *                                    [--expires <iso8601>] [--tokens-out <file>]
 *
 * Defaults come from HANDOFF_MCP_REGISTRY and HANDOFF_MCP_DB. Raw tokens are printed once
 * to stdout, or written to --tokens-out (mode 0600, refuses to overwrite). Treat them as
 * secrets: hand the reviewer token to directory review only through the portal's private
 * field, never in git, issues or chat.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

import { loadConfig } from "../dist/src/config.js";
import { enableAgent, issueToken } from "../dist/src/provision.js";
import { createRuntime } from "../dist/src/runtime.js";

const { values } = parseArgs({
  options: {
    registry: { type: "string" },
    db: { type: "string" },
    expires: { type: "string" },
    "tokens-out": { type: "string" },
  },
  strict: true,
});

const config = loadConfig({
  ...process.env,
  ...(values.registry ? { HANDOFF_MCP_REGISTRY: values.registry } : {}),
  ...(values.db ? { HANDOFF_MCP_DB: values.db } : {}),
});
const expires = values.expires ?? new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().replace(/\.\d{3}Z$/u, "Z");

for (const file of [config.registryFile, config.databaseFile, values["tokens-out"]].filter(Boolean)) {
  if (existsSync(file)) {
    process.stderr.write(`Refusing to seed: ${file} already exists. The demo seed only runs on a fresh volume.\n`);
    process.exit(1);
  }
}

// Synthetic identities. The operator is the human lead; the others stand in for agents.
const REGISTRY = `# Agent Handoff Board demo workspace (synthetic identities, single tenant).
# Generated by scripts/board-demo-seed.mjs. Tokens are stored as SHA-256 digests only.
version: 1
agents:
  - id: demo-operator
    display_name: Demo Operator (human lead)
    enabled: false
    send_to: [demo-planner, demo-coder, demo-reviewer]
    receive_from: [demo-planner, demo-coder, demo-reviewer]
    disclosure_ceiling: restricted
  - id: demo-planner
    display_name: Demo Planner agent
    enabled: false
    send_to: [demo-operator, demo-coder]
    receive_from: [demo-operator]
    disclosure_ceiling: internal
  - id: demo-coder
    display_name: Demo Coder agent
    enabled: false
    send_to: [demo-operator, demo-reviewer]
    receive_from: [demo-operator, demo-planner, demo-reviewer]
    disclosure_ceiling: internal
  - id: demo-reviewer
    display_name: Demo Reviewer agent
    enabled: false
    send_to: [demo-operator, demo-coder]
    receive_from: [demo-operator, demo-coder]
    disclosure_ceiling: public-safe
`;

const IDENTITIES = ["demo-operator", "demo-planner", "demo-coder", "demo-reviewer"];

mkdirSync(path.dirname(config.registryFile), { recursive: true, mode: 0o700 });
writeFileSync(config.registryFile, REGISTRY, { encoding: "utf8", flag: "wx", mode: 0o600 });
const tokens = {};
for (const id of IDENTITIES) {
  tokens[id] = (await issueToken(config.registryFile, id, expires)).token;
  await enableAgent(config.registryFile, id);
}

const { registry, store, service } = createRuntime(config);
await registry.current();

function draft(recipient, title, summary, request, extra = {}) {
  return {
    recipient,
    title,
    summary,
    request,
    contextRefs: [],
    artifactRefs: [],
    tags: ["demo"],
    sensitivity: "internal",
    priority: "normal",
    ...extra,
  };
}

const seeded = [];
try {
  const plan = await service.send("demo-operator", draft(
    "demo-planner",
    "Plan the v0.2 release checklist",
    "We want a short, ordered checklist for the next release of the demo service.",
    "List the release steps, owners and checks. Done when the checklist is attached as an artifact reference.",
    { priority: "high", contextRefs: ["repo:demo/agent-service", "milestone:v0.2"], idempotencyKey: "demo-seed-plan" },
  ));
  await service.acknowledge("demo-planner", plan.id, "Taking this; checklist by end of day.");
  seeded.push(["accepted", plan]);

  const fix = await service.send("demo-planner", draft(
    "demo-coder",
    "Fix the flaky login end-to-end test",
    "The login e2e test fails about one run in ten on CI with a timeout.",
    "Find the cause and fix it. Done when twenty consecutive local runs pass.",
    { contextRefs: ["test:e2e/login.test.ts", "log:ci-run-1842"], parentId: plan.id, idempotencyKey: "demo-seed-fix" },
  ));
  await service.acknowledge("demo-coder", fix.id);
  await service.updateStatus("demo-coder", fix.id, "completed", "Race on session cookie fixed; 20/20 runs green. See branch demo/fix-login-race.");
  seeded.push(["completed", fix]);

  const review = await service.send("demo-coder", draft(
    "demo-reviewer",
    "Review the rate limit headers change",
    "Adds standard RateLimit headers to every response.",
    "Review the change for correctness and missing tests. Done when you approve or list requested changes.",
    { sensitivity: "public-safe", artifactRefs: ["pr:demo/agent-service#42"], idempotencyKey: "demo-seed-review" },
  ));
  seeded.push(["queued", review]);

  const rotate = await service.send("demo-operator", draft(
    "demo-coder",
    "Rotate the staging service credentials",
    "Quarterly rotation of the staging credentials. No credential values are included here.",
    "Rotate and confirm the services restart cleanly. Done when the old credentials are rejected.",
    { priority: "urgent", idempotencyKey: "demo-seed-rotate" },
  ));
  await service.acknowledge("demo-coder", rotate.id);
  await service.updateStatus("demo-coder", rotate.id, "blocked", "Needs a maintenance window approved by the operator.");
  seeded.push(["blocked", rotate]);

  const notes = await service.send("demo-operator", draft(
    "demo-reviewer",
    "Draft public release notes",
    "Release notes for v0.2, for the public changelog.",
    "Draft release notes from the merged pull requests. Done when the draft is linked here.",
    { sensitivity: "public-safe", priority: "low", idempotencyKey: "demo-seed-notes" },
  ));
  seeded.push(["queued", notes]);
} finally {
  store.close();
}

process.stdout.write(`Demo workspace seeded.\n  registry: ${config.registryFile}\n  database: ${config.databaseFile}\n  tokens expire: ${expires}\n`);
for (const [status, handoff] of seeded) {
  process.stdout.write(`  ${status.padEnd(9)} ${handoff.sender} -> ${handoff.recipient}: ${handoff.title}\n`);
}

if (values["tokens-out"]) {
  const out = path.resolve(values["tokens-out"]);
  writeFileSync(out, `${JSON.stringify(tokens, null, 2)}\n`, { encoding: "utf8", flag: "wx", mode: 0o600 });
  process.stdout.write(`Raw tokens written once to ${out} (mode 0600). Move them to a secret store and delete the file.\n`);
} else {
  process.stdout.write("Raw tokens (shown once, never stored):\n");
  for (const [id, token] of Object.entries(tokens)) process.stdout.write(`  ${id}: ${token}\n`);
}
